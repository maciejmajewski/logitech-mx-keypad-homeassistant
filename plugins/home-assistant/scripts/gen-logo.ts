// Rasterises the Home Assistant logomark (assets/, CC BY-NC-SA 4.0) into
//   package/metadata/Icon256x256.png   the plugin icon: colour logomark in a centred 192x192 area
//   src/logo.ts                        a 48x48 alpha mask of the logomark for the connection key face
// Needs rsvg-convert (brew install librsvg). Run: node scripts/gen-logo.ts
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { inflateSync } from 'node:zlib';
import { Canvas } from '../src/png.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const colour = join(root, 'assets', 'ha-logomark-color.svg');
const mono = join(root, 'assets', 'ha-logomark-mono.svg');

// rsvg-convert writes a PNG; decode it with our own minimal reader (it emits
// 8-bit RGBA, possibly several IDAT chunks, with per-row filters).
function rasterise(svg: string, size: number): { width: number; height: number; rgba: Buffer } {
  const png = execFileSync('rsvg-convert', ['-w', String(size), '-h', String(size), '-f', 'png', svg]);
  return decodePng(png);
}

function decodePng(png: Buffer): { width: number; height: number; rgba: Buffer } {
  let o = 8;
  const idat: Buffer[] = [];
  let width = 0;
  let height = 0;
  let colourType = 0;
  while (o < png.length) {
    const len = png.readUInt32BE(o);
    const type = png.toString('ascii', o + 4, o + 8);
    const data = png.subarray(o + 8, o + 8 + len);
    if (type === 'IHDR') {
      width = data.readUInt32BE(0);
      height = data.readUInt32BE(4);
      if (data[8] !== 8) throw new Error(`unsupported bit depth ${data[8]}`);
      colourType = data[9];
    }
    if (type === 'IDAT') idat.push(data);
    o += 12 + len;
  }
  const bpp = colourType === 6 ? 4 : colourType === 2 ? 3 : colourType === 4 ? 2 : 1;
  const raw = inflateSync(Buffer.concat(idat));
  const stride = width * bpp;
  const out = Buffer.alloc(width * height * 4);
  let prev = Buffer.alloc(stride);
  for (let y = 0; y < height; y++) {
    const filter = raw[y * (stride + 1)];
    const row = Buffer.from(raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1)));
    for (let i = 0; i < stride; i++) {
      const a = i >= bpp ? row[i - bpp] : 0;
      const b = prev[i];
      const c = i >= bpp ? prev[i - bpp] : 0;
      let v = row[i];
      if (filter === 1) v += a;
      else if (filter === 2) v += b;
      else if (filter === 3) v += (a + b) >> 1;
      else if (filter === 4) {
        const p = a + b - c;
        const pa = Math.abs(p - a);
        const pb = Math.abs(p - b);
        const pc = Math.abs(p - c);
        v += pa <= pb && pa <= pc ? a : pb <= pc ? b : c;
      }
      row[i] = v & 0xff;
    }
    for (let x = 0; x < width; x++) {
      const i = x * bpp;
      const d = (y * width + x) * 4;
      if (bpp === 4) row.copy(out, d, i, i + 4);
      else if (bpp === 3) {
        row.copy(out, d, i, i + 3);
        out[d + 3] = 255;
      } else if (bpp === 2) {
        out[d] = out[d + 1] = out[d + 2] = row[i];
        out[d + 3] = row[i + 1];
      } else {
        out[d] = out[d + 1] = out[d + 2] = row[i];
        out[d + 3] = 255;
      }
    }
    prev = row;
  }
  return { width, height, rgba: out };
}

// Plugin icon: the colour logomark, 192 px, centred on a transparent 256 canvas.
const ICON = 256;
const INNER = 192;
const logo = rasterise(colour, INNER);
const icon = new Canvas(ICON, ICON);
for (let y = 0; y < INNER; y++) {
  for (let x = 0; x < INNER; x++) {
    const p = (y * INNER + x) * 4;
    const a = logo.rgba[p + 3];
    if (a > 0) icon.set((ICON - INNER) / 2 + x, (ICON - INNER) / 2 + y, [logo.rgba[p], logo.rgba[p + 1], logo.rgba[p + 2]], a);
  }
}
writeFileSync(join(root, 'package', 'metadata', 'Icon256x256.png'), icon.toPng());

// Key-face mask: the monochrome logomark's alpha channel at 48 px.
const MASK = 48;
const mask = rasterise(mono, MASK);
const alpha = Buffer.alloc(MASK * MASK);
for (let i = 0; i < MASK * MASK; i++) alpha[i] = mask.rgba[i * 4 + 3];
const header = readFileSync(join(root, 'assets', 'README.md'), 'utf8').split('\n')[0];
writeFileSync(
  join(root, 'src', 'logo.ts'),
  `// Generated by scripts/gen-logo.ts from assets/ha-logomark-mono.svg; do not edit.
// ${header.replace(/^#\s*/, '')}: Home Assistant logomark, CC BY-NC-SA 4.0, trademark of the
// Open Home Foundation. See assets/README.md and NOTICE.md.
// A ${MASK}x${MASK} alpha mask (0..255 per pixel, row-major), base64.
export const LOGO_SIZE = ${MASK};
export const LOGO_ALPHA = Buffer.from(
  '${alpha.toString('base64')}',
  'base64',
);
`,
);
console.log(`wrote Icon256x256.png (${logo.width}px logomark) and src/logo.ts (${MASK}x${MASK} mask)`);
