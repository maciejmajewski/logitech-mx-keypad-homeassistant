export function iconForMdi(mdi: string | undefined): IconName | undefined {
  if (!mdi) return undefined;
  const name = mdi.replace(/^mdi:/, '').toLowerCase();
  for (const [prefix, icon] of MDI) if (name.startsWith(prefix)) return icon;
  return undefined;
}

