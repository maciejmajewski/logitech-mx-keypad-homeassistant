export function domainOf(entityId: string): string {
  return entityId.split('.')[0] ?? '';
}

// Picks the glyph for an entity. `override` is the config entry's `icon`
// (a glyph name or an mdi: name); `attributes` come from the entity state.
export function iconFor(entityId: string, attributes: Record<string, unknown> = {}, override?: string): IconName {
  if (override) {
    if (isIconName(override)) return override;
    const mapped = iconForMdi(override);
    if (mapped) return mapped;
  }
  const domain = domainOf(entityId);
  const fromAttribute = iconForMdi(typeof attributes.icon === 'string' ? attributes.icon : undefined);
  if (fromAttribute) return fromAttribute;
  const deviceClass = typeof attributes.device_class === 'string' ? attributes.device_class : undefined;
  if (deviceClass && DEVICE_CLASS[deviceClass]) return DEVICE_CLASS[deviceClass];
  if (domain === 'lock') return 'lock';
  return DOMAIN[domain] ?? 'question';
}

// A bitmap as an SVG path of unit squares, for the static SVG assets.
export function pixelPath(rows: readonly string[], scale: number, ox = 0, oy = 0): string {
  const parts: string[] = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] === '#') parts.push(`M${ox + x * scale} ${oy + y * scale}h${scale}v${scale}h-${scale}z`);
    }
  });
  return parts.join('');
}
